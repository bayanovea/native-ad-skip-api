// Package transcript defines the JSONL transcript format: a single "meta" line
// followed by one "cue" line per phrase. One file per video.
package transcript

import (
	"bufio"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"time"

	"odedohbest/video-calculate/ai/vtt"
)

// TrackType classifies the subtitle track used for the transcript.
type TrackType string

const (
	TrackManual  TrackType = "manual"  // uploaded by the author (not detectable from yt-dlp output yet)
	TrackAuto    TrackType = "auto"    // generated by the platform
	TrackNone    TrackType = "none"    // video has no subtitle track
	TrackUnknown TrackType = "unknown" // a track exists but carries no label
	// TrackUntyped (empty) marks a transcript built offline by `collapse` without
	// metadata; `fetch` completes it. Never a final value.
	TrackUntyped TrackType = ""
)

// Meta is the first line of a transcript file.
type Meta struct {
	Kind      string    `json:"kind"` // always "meta"
	NativeID  string    `json:"native_id"`
	Provider  string    `json:"provider"` // "prv", "yt", "rt"
	Title     string    `json:"title,omitempty"`
	Duration  float64   `json:"duration"` // seconds, from yt-dlp metadata
	Lang      string    `json:"lang,omitempty"`
	TrackType TrackType `json:"track_type"`
	TrackName string    `json:"track_name,omitempty"`
	Cues      int       `json:"cues"`
	Words     int       `json:"words"`
	FetchedAt time.Time `json:"fetched_at"`
}

type cueLine struct {
	Kind string `json:"kind"`
	vtt.Cue
}

// Write serialises meta and cues as JSONL. Meta.Cues/Words are filled in here.
func Write(w io.Writer, meta Meta, cues []vtt.Cue) error {
	meta.Kind = "meta"
	meta.Cues = len(cues)
	meta.Words = vtt.Words(cues)
	enc := json.NewEncoder(w)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(meta); err != nil {
		return err
	}
	for _, c := range cues {
		if err := enc.Encode(cueLine{Kind: "cue", Cue: c}); err != nil {
			return err
		}
	}
	return nil
}

// WriteFile writes atomically: to a temp file in the same dir, then rename.
func WriteFile(path string, meta Meta, cues []vtt.Cue) error {
	tmp := path + ".tmp"
	f, err := os.Create(tmp)
	if err != nil {
		return err
	}
	if err := Write(f, meta, cues); err != nil {
		f.Close()
		os.Remove(tmp)
		return err
	}
	if err := f.Close(); err != nil {
		os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, path)
}

// Read parses a transcript file back.
func Read(r io.Reader) (Meta, []vtt.Cue, error) {
	var meta Meta
	var cues []vtt.Cue
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	first := true
	for sc.Scan() {
		line := sc.Bytes()
		if len(line) == 0 {
			continue
		}
		if first {
			first = false
			if err := json.Unmarshal(line, &meta); err != nil || meta.Kind != "meta" {
				return meta, nil, fmt.Errorf("transcript: first line is not meta: %v", err)
			}
			continue
		}
		var c cueLine
		if err := json.Unmarshal(line, &c); err != nil {
			return meta, nil, err
		}
		cues = append(cues, c.Cue)
	}
	return meta, cues, sc.Err()
}
